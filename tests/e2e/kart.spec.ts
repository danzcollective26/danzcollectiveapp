test('The focused joystick delegates gas and brake to the racing keyboard',async({page})=>{
  await page.goto('/test?seccion=arcade&juego=kart')
  await page.getByRole('button',{name:'SALIR A PISTA',exact:true}).click()
  await expect(page.locator('.kart-game')).toHaveAttribute('data-phase','playing',{timeout:8000})
  await page.getByRole('button',{name:'P1 Joystick',exact:true}).focus()
  await page.keyboard.down('w')
  await expect.poll(async()=>Number(await page.locator('.kart-game').getAttribute('data-speed'))).toBeGreaterThan(30)
  await page.keyboard.up('w')
  await page.keyboard.down('s')
  await expect.poll(async()=>Number(await page.locator('.kart-game').getAttribute('data-speed'))).toBeLessThan(1)
  await page.keyboard.up('s')
})
