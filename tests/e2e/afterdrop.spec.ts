import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('danz-yeppo-welcome-v1', 'done')
    sessionStorage.setItem('danz-yeppo-visit-peek-v1', 'done')
    Element.prototype.requestFullscreen = () => Promise.reject(new DOMException('Unavailable', 'NotSupportedError'))
  })
})

test('After Drop opens, accepts a lane and a pause, then returns to the library', async ({ page }) => {
  await page.goto('/?seccion=arcade&juego=afterdrop')
  const menu = page.locator('.arcade-console-menu')
  await expect(menu.getByRole('heading', { name: 'AFTER DROP' })).toBeVisible()
  await expect(menu).toContainText('Récord de este navegador')
  await menu.getByRole('button', { name: /CAER AL DROP/ }).click()
  const game = page.locator('.ad-game')
  await expect(game).toHaveAttribute('data-status', 'playing')
  await expect(page.locator('.yeppo')).toHaveCount(0)
  const lane = page.getByRole('button', { name: 'Carril izquierdo', exact: true })
  await expect(lane).toBeEnabled()
  const box = await lane.boundingBox()
  expect(box!.width).toBeGreaterThanOrEqual(44)
  expect(box!.height).toBeGreaterThanOrEqual(44)
  await lane.click()
  await expect(lane).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Carril central', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const extract = page.getByRole('button', { name: /Extraer botín|Sin botín que extraer/ })
  await expect(extract).toBeVisible()
  expect((await extract.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(menu.getByRole('button', { name: /REANUDAR/ })).toBeVisible()
  await expect(game).toHaveAttribute('data-status', 'paused')
  await page.getByRole('button', { name: 'Volver a la biblioteca ARCADANZ', exact: true }).click()
  await expect(page.getByLabel('Biblioteca ARCADANZ')).toBeVisible()
  await expect(page.locator('.ad-game')).toHaveCount(0)
  expect(await page.locator('body').evaluate(element => element.style.overflow)).not.toBe('hidden')
})

test('the mobile test route opens After Drop without leaving /test', async ({ page }) => {
  await page.goto('/test')
  await page.getByRole('button', { name: /05 \/ RITMO · EXTRACCIÓN AFTER DROP/ }).click()
  await expect(page).toHaveURL(/juego=afterdrop/)
  await expect(page.locator('.arcade-console-menu').getByRole('heading', { name: 'AFTER DROP' })).toBeVisible()
  expect(new URL(page.url()).pathname).toBe('/test')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
})
